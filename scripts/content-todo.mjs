#!/usr/bin/env node
/**
 * Generates /CONTENT-TODO.md.
 *
 * Collects every fact this build was not given: PROVIDE tokens written into
 * pages, and site_settings rows whose value is still a PROVIDE token. Nothing
 * about this hospital was invented, so this file is the complete list of what
 * has to be supplied before the site goes live.
 *
 *   node scripts/content-todo.mjs
 */

import { readFileSync, readdirSync, statSync, writeFileSync } from "node:fs";
import { join, relative, sep } from "node:path";

function loadEnv(file) {
  let text;
  try {
    text = readFileSync(file, "utf8");
  } catch {
    return;
  }
  for (const line of text.split(/\r?\n/)) {
    const at = line.indexOf("=");
    if (at <= 0 || line.trim().startsWith("#")) continue;
    const key = line.slice(0, at).trim();
    if (process.env[key] === undefined) process.env[key] = line.slice(at + 1);
  }
}

loadEnv(".env.local");

const ROOT = process.cwd();
const EXTENSIONS = new Set([".ts", ".tsx"]);

function walk(dir, files = []) {
  let entries;
  try {
    entries = readdirSync(dir);
  } catch {
    return files;
  }
  for (const entry of entries) {
    const full = join(dir, entry);
    if (statSync(full).isDirectory()) {
      if ([".next", "node_modules", ".git"].includes(entry)) continue;
      walk(full, files);
    } else if (EXTENSIONS.has(entry.slice(entry.lastIndexOf(".")))) {
      files.push(full);
    }
  }
  return files;
}

/** Turn a file path into the route a reader would recognise. */
function routeOf(rel) {
  if (!rel.startsWith("src/app/")) return rel;
  let route = rel
    .slice("src/app".length)
    .replace(/\/(page|layout)\.tsx$/, "")
    .replace(/\/\([^)]+\)/g, "");
  if (route === "") route = "/";
  return route;
}

const inPages = [];

for (const file of walk(join(ROOT, "src"))) {
  const text = readFileSync(file, "utf8");
  const rel = relative(ROOT, file).split(sep).join("/");

  const componentUse = /<Provide\s[^>]*note=\{?["'`]([^"'`]+)["'`]/g;
  let match;
  while ((match = componentUse.exec(text)) !== null) {
    inPages.push({
      note: match[1],
      file: rel,
      route: routeOf(rel),
      line: text.slice(0, match.index).split("\n").length,
    });
  }

  // Library code manipulates the token format itself, so its own occurrences
  // are machinery rather than missing content.
  if (rel.startsWith("src/lib/") || rel.endsWith("Provide.tsx")) continue;

  const literal = /\[\[PROVIDE:\s*([^\]]+?)\s*\]\]/g;
  while ((match = literal.exec(text)) !== null) {
    inPages.push({
      note: match[1],
      file: rel,
      route: routeOf(rel),
      line: text.slice(0, match.index).split("\n").length,
    });
  }
}

const run = async () => {
  const settings = [];
  const url = process.env.NEXT_PUBLIC_SUPABASE_URL;
  const key = process.env.NEXT_PUBLIC_SUPABASE_ANON_KEY;

  if (url && key) {
    try {
      const response = await fetch(
        `${url}/rest/v1/site_settings?select=key,value,label`,
        {
          headers: { apikey: key, Authorization: `Bearer ${key}` },
        },
      );
      if (response.ok) {
        for (const row of await response.json()) {
          if (String(row.value).trim().startsWith("[[PROVIDE:")) {
            const note = /^\[\[PROVIDE:\s*(.*?)\s*\]\]$/.exec(String(row.value).trim());
            settings.push({ key: row.key, label: row.label, note: note?.[1] ?? "" });
          }
        }
      }
    } catch {
      // Offline. The page section below is still generated.
    }
  }

  const byNote = new Map();
  for (const item of inPages) {
    const existing = byNote.get(item.note) ?? { note: item.note, places: [] };
    existing.places.push(`${item.route} (${item.file}:${item.line})`);
    byNote.set(item.note, existing);
  }
  const grouped = [...byNote.values()].sort((a, b) => a.note.localeCompare(b.note));

  const total = grouped.length + settings.length;

  const lines = [
    "# Content still to be supplied",
    "",
    "Nothing about this hospital has been invented. Every fact that was not",
    "supplied appears on the site as a boxed `[[PROVIDE: ...]]` placeholder,",
    "and every one of them is listed here.",
    "",
    `Generated by \`npm run content:todo\`. **${total} items outstanding.**`,
    "",
    "---",
    "",
    "## 1. Editable in the portal",
    "",
    settings.length === 0
      ? "Nothing outstanding, or the database was unreachable when this ran."
      : [
          "Fill these in at **/portal/admin, Site settings**. No deployment needed;",
          "they appear on the public site as soon as they are saved.",
          "",
          "| Setting | What is needed |",
          "| --- | --- |",
          ...settings.map((row) => `| ${row.label} (\`${row.key}\`) | ${row.note} |`),
        ].join("\n"),
    "",
    "## 2. Written into pages",
    "",
    grouped.length === 0
      ? "Nothing outstanding."
      : [
          "These are in the page source. Supply the text and a developer replaces",
          "the placeholder, or move the value into `site_settings` so the portal can",
          "edit it in future.",
          "",
          ...grouped.flatMap((item) => [
            `### ${item.note}`,
            "",
            ...item.places.map((place) => `- \`${place}\``),
            "",
          ]),
        ].join("\n"),
    "",
    "---",
    "",
    "## Assumptions that must be confirmed",
    "",
    "These are not missing content. They are numbers this build had to choose",
    "because the hospital has not published them, and they change how many",
    "patients are seen. **Confirm each one before the site goes live.**",
    "",
    "| Assumption | Value used | Why | Where to change it |",
    "| --- | --- | --- | --- |",
    "| Minutes per patient | 10 | The hospital publishes session times but not throughput. | /portal/reception → Availability |",
    "| Tokens per session | 18 | Derived: a three-hour session at 10 minutes each. | /portal/reception → Availability |",
    "| Biochemistry and Pathology take patient bookings | Yes | The doctors PDF lists these two under \"TIMMING\" rather than \"OPD TIMMING\", which may mean they are diagnostic consultants rather than OPD clinics. If so, deactivate their weekly sessions. | /portal/reception → Availability |",
    "| Booking window | 7 days | From the brief, not from the hospital. | /portal/reception → Booking rules |",
    "| Same-day cutoff | 60 minutes before the session ends | From the brief. | /portal/reception → Booking rules |",
    "| Appointments per phone per day | 2 | From the brief. | /portal/reception → Booking rules |",
    "",
    "## Also outstanding, and not a PROVIDE token",
    "",
    "- **The emergency number is the most important gap.** It is on the masthead of",
    "  every page, on /emergency and in the footer, and it is the one number a",
    "  patient needs in a hurry. The hospital does not publish it anywhere online.",
    "- **Administration directory.** Real names and designations, added through",
    "  /portal/reception → Announcements is not the place; these go in the",
    "  `administration` table via technical support.",
    "- **Doctor photographs.** Optional. No stock photography is used, so a doctor",
    "  without a photograph simply has none.",
    "- **Announcements.** None are published. The hospital's own announcements page",
    "  is under construction, so there was nothing to carry over.",
    "",
    "---",
    "",
    "## Where the content came from",
    "",
    "Everything factual on this site was taken from the hospital's own published",
    "material, not written for it:",
    "",
    "| Source | Supplied |",
    "| --- | --- |",
    "| `spmsh.iitkgp.ac.in/contact.php` | Official name, legal entity, address, three telephone numbers |",
    "| `spmsh.iitkgp.ac.in/about.php` | Description, superspeciality scope, stated aims |",
    "| `spmsh.iitkgp.ac.in/service.php` | OPD session times, the five upcoming investigation types, IPD status |",
    "| `spmsh.iitkgp.ac.in/avert/Doctors Profile.pdf` | All 11 consultants: names, specialities, qualifications, OPD days and times |",
    "| `spmsh.iitkgp.ac.in/image/hms1.jpg` | The building photograph on /about |",
    "| `spmsh.iitkgp.ac.in/image/logoif.png` | The masthead lockup and the crest |",
    "",
  ];

  writeFileSync(join(ROOT, "CONTENT-TODO.md"), `${lines.join("\n")}\n`, "utf8");
  process.stdout.write(
    `content-todo — ${total} outstanding (${settings.length} in settings, ${grouped.length} in pages)\n`,
  );
};

await run();
